"""Pin the behavior the colab notebook had before its definitions moved into packages.

``golden_notebook_protocol.json`` was generated by executing the notebook's own
``make_protocol``/``protocol_hash`` before the refactor.
"""
import json
from pathlib import Path

import pytest

from team_pipeline import data

ROOT = Path(__file__).resolve().parents[1]
GOLDEN = json.loads((Path(__file__).parent / "golden_notebook_protocol.json").read_text())


def imagenette_protocol():
    return data.make_protocol(labels=data.CLASS_LABELS, calibration_per_class=2,
                              validation_per_class=2, test_per_class=500)


def test_imagenette_protocol_matches_notebook_golden_values():
    protocol = imagenette_protocol()
    assert data.protocol_hash(protocol) == GOLDEN["protocol_sha256"]
    assert list(data.CLASS_LABELS) == GOLDEN["class_labels"]
    assert {k: len(v) for k, v in protocol["splits"].items()} == GOLDEN["split_sizes"]
    assert protocol["settings"] == GOLDEN["settings"]
    for name, pairs in protocol["splits"].items():
        assert pairs[:3] == GOLDEN["first_pairs"][name]
        assert pairs[-1] == GOLDEN["last_pairs"][name]


def test_load_protocol_accepts_dict_copy_and_path(tmp_path):
    protocol = imagenette_protocol()
    loaded = data.load_protocol(protocol)
    assert loaded == protocol and loaded is not protocol
    loaded["splits"]["test"].append([1, 2])  # must not leak into the caller's dict
    assert len(protocol["splits"]["test"]) == 5000
    path = tmp_path / "protocol.json"
    path.write_text(json.dumps(protocol))
    assert data.load_protocol(path) == protocol


def test_default_protocol_still_matches_team_protocol_json():
    assert data.make_protocol(fid_per_class=1) == json.loads((ROOT / "team_protocol.json").read_text())


def test_load_protocol_rejects_seed_leakage_and_unknown_splits():
    protocol = imagenette_protocol()
    leaky = json.loads(json.dumps(protocol))
    leaky["splits"]["validation"][0][1] = leaky["splits"]["calibration"][0][1]
    with pytest.raises(ValueError):
        data.load_protocol(leaky)
    extra = json.loads(json.dumps(protocol))
    extra["splits"]["surprise"] = [[0, 99_999_999]]
    with pytest.raises(ValueError):
        data.load_protocol(extra)


def test_sampler_seed_offset_is_the_protocol_constant():
    assert data.SAMPLER_SEED_OFFSET == GOLDEN["settings"]["sampler_seed_offset"]
    assert data.MAX_SEED == 2**63 - data.SAMPLER_SEED_OFFSET
